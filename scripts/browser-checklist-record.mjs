import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {readFile,mkdir} from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:375,height:812}});
const page=await context.newPage(),errors=[];
page.on('pageerror',error=>errors.push(error.message));
await context.addInitScript(()=>{
 Object.defineProperty(navigator,'canShare',{configurable:true,value:()=>true});
 Object.defineProperty(navigator,'share',{configurable:true,value:async data=>{
  if(window.failShare)throw new DOMException('Unavailable','NotAllowedError');
  if(window.cancelShare)throw new DOMException('Cancelled','AbortError');
  window.sharedRecord={title:data.title,text:data.text,json:await data.files[0].text()};
 }});
});
const saved=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('tempalist:data')).checklists[0]);
try{
 await page.goto('http://127.0.0.1:4173');
 await page.getByRole('button',{name:/工場の始業前点検/}).click();
 await page.getByLabel('タイトル',{exact:true}).fill('実験の準備 🧪');
 await page.getByRole('button',{name:'作成する',exact:true}).click();
 await page.locator('#dialog').waitFor({state:'hidden'});
 const route=await page.evaluate(()=>location.hash);
 assert.equal(await page.locator('.brand').evaluate(el=>getComputedStyle(el).borderBottomWidth),'1px');
 await page.getByRole('textbox',{name:'リスト全体の備考'}).fill('完了前の備考\n申し送り');
 await page.getByRole('checkbox').first().check();
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('tempalist:data')).checklists[0].items[0].checked);
 assert.equal(await page.getByRole('textbox',{name:'リスト全体の備考'}).inputValue(),'完了前の備考\n申し送り');
 await page.getByRole('link',{name:'設定',exact:true}).click();
 await page.getByRole('heading',{name:'設定とデータ'}).waitFor();
 await page.getByRole('link',{name:'リスト',exact:true}).click();
 assert.equal(await page.getByRole('textbox',{name:'リスト全体の備考'}).inputValue(),'完了前の備考\n申し送り');
 await page.getByRole('button',{name:'メール・記録を書き出す',exact:true}).click();
 await page.locator('#record-body').waitFor();
 assert.equal((await saved()).remarks,'完了前の備考\n申し送り');
 assert.match(await page.locator('#record-body').inputValue(),/完了日時: 未完了/);
 await page.getByRole('button',{name:'メールアプリへ共有（JSON付き）',exact:true}).click();
 await page.waitForFunction(()=>window.sharedRecord);
 const shared=await page.evaluate(()=>window.sharedRecord);
 assert.equal(shared.title,'実験の準備 🧪');assert.equal(JSON.parse(shared.json).checklist.settledAt,null);
 await page.evaluate(()=>window.failShare=true);
 await page.locator('#record-share').click();await page.locator('.form-error').filter({hasText:'共有できませんでした'}).waitFor();
 assert.equal(await page.locator('.record-alternatives').getAttribute('open'),'');
 await page.getByRole('button',{name:'閉じる',exact:true}).click();
 await page.getByRole('textbox',{name:'リスト全体の備考'}).fill('完了時に保存する備考');
 await page.getByRole('button',{name:'完了を確定する',exact:true}).click();
 await page.getByRole('button',{name:'このまま確定する',exact:true}).click();
 await page.locator('#dialog').waitFor({state:'hidden'});
 await page.locator('.list-card').first().click();
 assert.equal(await page.getByRole('textbox',{name:'リスト全体の備考'}).isEditable(),true);
 const completed=await saved();assert.equal(completed.remarks,'完了時に保存する備考');assert.ok(completed.settledAt);
 await page.getByRole('textbox',{name:'リスト全体の備考'}).fill('完了後の追記 <script>\n確認者：山田');
 await page.getByRole('button',{name:'備考を保存',exact:true}).click();
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('tempalist:data')).checklists[0].remarks.startsWith('完了後'));
 await page.reload();
 assert.equal((await saved()).settledAt,completed.settledAt);
 assert.match(await page.getByRole('textbox',{name:'リスト全体の備考'}).inputValue(),/完了後の追記/);
 assert.equal(await page.getByRole('checkbox').first().isDisabled(),true);
 await mkdir('artifacts',{recursive:true});
 await page.getByRole('textbox',{name:'リスト全体の備考'}).scrollIntoViewIfNeeded();
 await page.screenshot({path:'artifacts/checklist-remarks-mobile.png'});
 await page.getByRole('button',{name:'メール・記録を書き出す',exact:true}).click();
 let downloading=page.waitForEvent('download');await page.locator('#record-json').click();let download=await downloading;
 const json=JSON.parse(await readFile(await download.path(),'utf8'));
 assert.equal(json.checklist.settledAt,completed.settledAt);assert.match(json.checklist.remarks,/完了後/);
 assert.deepEqual(json.checklist.items,completed.items);
 await page.locator('.record-alternatives summary').click();
 downloading=page.waitForEvent('download');await page.locator('#record-eml').click();download=await downloading;
 const eml=await readFile(await download.path(),'utf8');assert.match(eml,/Content-Type: application\/json/);
 await download.saveAs('artifacts/checklist-record.eml');
 await page.getByRole('button',{name:'閉じる',exact:true}).click();
 // A different tab can edit remarks; a stale draft must neither be overwritten nor overwrite it.
 await page.getByRole('textbox',{name:'リスト全体の備考'}).fill('このタブの未保存入力');
 const other=await context.newPage();await other.goto('http://127.0.0.1:4173/'+route);
 await other.getByRole('textbox',{name:'リスト全体の備考'}).fill('別タブで保存');
 await other.getByRole('button',{name:'備考を保存',exact:true}).click();
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('tempalist:data')).checklists[0].remarks==='別タブで保存');
 assert.equal(await page.getByRole('textbox',{name:'リスト全体の備考'}).inputValue(),'このタブの未保存入力');
 await page.getByRole('button',{name:'メール・記録を書き出す',exact:true}).click();
 await page.locator('#toast').filter({hasText:'別の画面で更新'}).waitFor();
 assert.equal(await page.locator('#dialog').isVisible(),false);
 assert.equal((await saved()).remarks,'別タブで保存');
 assert.equal((await saved()).settledAt,completed.settledAt);
 // No-share environments retain manual and .eml export paths.
 await other.evaluate(()=>Object.defineProperty(navigator,'canShare',{configurable:true,value:()=>false}));
 await other.getByRole('button',{name:'メール・記録を書き出す',exact:true}).click();
 await other.locator('#record-json').waitFor();assert.equal(await other.locator('#record-share').count(),0);
 await other.getByRole('button',{name:'閉じる',exact:true}).click();
 await other.setViewportSize({width:1280,height:900});
 assert.equal(await other.locator('.app-header').evaluate(el=>getComputedStyle(el).borderBottomWidth),'1px');
 assert.equal(await other.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log('Checklist records: inline remarks before/after completion, unsaved drafts, tab conflicts, pending/settled JSON, share/fallback, EML download, unchanged timestamps: OK');
}finally{await browser.close();}
